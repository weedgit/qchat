#!/usr/bin/env node
/**
 * Read deploy/hosts.env and write per-app .env + desktop production.json.
 * Run after editing deploy/hosts.env:  node scripts/sync-hosts-env.js
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const HOSTS_FILE = path.join(ROOT, "deploy", "hosts.env");
const HOSTS_EXAMPLE = path.join(ROOT, "deploy", "hosts.env.example");

function parseEnvFile(filePath) {
  const out = {};
  if (!fs.existsSync(filePath)) return out;
  for (const raw of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim();
    let val = line.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

function req(env, key) {
  const val = String(env[key] || "").trim();
  if (!val) {
    throw new Error(`Missing ${key} in deploy/hosts.env`);
  }
  return val.replace(/\/$/, "");
}

function joinUrl(origin, subpath) {
  const base = origin.replace(/\/$/, "");
  const p = subpath.startsWith("/") ? subpath : `/${subpath}`;
  if (p === "/") return `${base}/`;
  return `${base}${p}`;
}

function write(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content);
  console.log(`  wrote ${path.relative(ROOT, filePath)}`);
}

function envBlock(header, lines) {
  const body = lines
    .map((entry) => {
      if (typeof entry === "string") return entry;
      const [k, v] = entry;
      return `${k}=${v}`;
    })
    .join("\n");
  return `${header}\n# Generated by scripts/sync-hosts-env.js — edit deploy/hosts.env and re-run.\n\n${body}\n`;
}

function main() {
  const source = fs.existsSync(HOSTS_FILE) ? HOSTS_FILE : HOSTS_EXAMPLE;
  if (!fs.existsSync(HOSTS_FILE)) {
    console.warn(
      "warn: deploy/hosts.env not found — using hosts.env.example (copy it first)"
    );
  }
  const h = parseEnvFile(source);

  const rchat = req(h, "RCHAT_ORIGIN");
  const xin = req(h, "XINCHAT_ORIGIN");
  const xinPath = String(h.XINCHAT_WEB_PATH || "/xin").replace(/\/$/, "") || "/xin";
  const xinWeb = joinUrl(xin, xinPath);
  const rchatLk = req(h, "RCHAT_LIVEKIT_URL");
  const xinLk = req(h, "XINCHAT_LIVEKIT_URL");
  const rchatUpdates = req(h, "RCHAT_DESKTOP_UPDATE_URL");
  const xinUpdates = req(h, "XINCHAT_DESKTOP_UPDATE_URL");
  const localRchat = h.LOCAL_RCHAT_WEB || "http://localhost:3000";
  const localXin = h.LOCAL_XINCHAT_WEB || "http://localhost:3001/xin";
  const localApi = h.LOCAL_API || "http://localhost:8080";

  console.log(`Syncing from ${path.relative(ROOT, source)}`);

  write(
    path.join(ROOT, "apps/web/.env"),
    envBlock("# Rchat web (apps/web)", [
      ["NEXT_PUBLIC_LIVEKIT_URL", rchatLk],
      "# NEXT_PUBLIC_API_URL=  (empty = same-origin via nginx)",
      ["NEXT_PUBLIC_RCHAT_ORIGIN", rchat],
      ["NEXT_PUBLIC_XINCHAT_ORIGIN", xin],
    ])
  );

  write(
    path.join(ROOT, "apps/xin-web/.env"),
    envBlock("# XinChat web (apps/xin-web)", [
      ["NEXT_PUBLIC_LIVEKIT_URL", xinLk],
      "# NEXT_PUBLIC_API_URL=  (empty = same-origin via nginx)",
      ["NEXT_PUBLIC_RCHAT_ORIGIN", rchat],
      ["NEXT_PUBLIC_XINCHAT_ORIGIN", xin],
    ])
  );

  write(
    path.join(ROOT, "apps/admin/.env"),
    envBlock("# Admin console (apps/admin)", [
      "# NEXT_PUBLIC_API_URL=  (empty = same-origin at /admin/)",
      ["NEXT_PUBLIC_RCHAT_ORIGIN", rchat],
    ])
  );

  write(
    path.join(ROOT, "apps/desktop/.env"),
    envBlock("# Rchat desktop dev shell", [
      ["QCHAT_WEB_URL", rchat],
      `# QCHAT_API_URL=${localApi}`,
      `# QCHAT_UPDATE_URL=${rchatUpdates}`,
    ])
  );

  write(
    path.join(ROOT, "apps/xin-desktop/.env"),
    envBlock("# XinChat desktop dev shell", [
      ["XINCHAT_WEB_URL", xinWeb],
      `# QCHAT_API_URL=${localApi}`,
      `# QCHAT_UPDATE_URL=${xinUpdates}`,
    ])
  );

  write(
    path.join(ROOT, "apps/mobile/.env"),
    envBlock("# Rchat mobile (Expo)", [
      ["EXPO_PUBLIC_API_URL", rchat],
      ["EXPO_PUBLIC_LIVEKIT_URL", rchatLk],
    ])
  );

  write(
    path.join(ROOT, "apps/xin-mobile/.env"),
    envBlock("# XinChat mobile (Expo)", [
      ["EXPO_PUBLIC_API_URL", xin],
      ["EXPO_PUBLIC_LIVEKIT_URL", xinLk],
      ["NEXT_PUBLIC_RCHAT_ORIGIN", rchat],
      ["NEXT_PUBLIC_XINCHAT_ORIGIN", xin],
    ])
  );

  write(
    path.join(ROOT, "apps/desktop/production.json"),
    `${JSON.stringify({ webUrl: rchat, updateUrl: rchatUpdates }, null, 2)}\n`
  );

  write(
    path.join(ROOT, "apps/xin-desktop/production.json"),
    `${JSON.stringify({ webUrl: xinWeb, updateUrl: xinUpdates }, null, 2)}\n`
  );

  console.log("\nDone. Rebuild desktop/mobile installers if you changed production URLs.");
}

main();
